import { MongoMemoryReplSet } from "mongodb-memory-server";
import mongoose from "mongoose";
import bcrypt from "bcryptjs";
import { randomUUID } from "node:crypto";
import { spawn } from "node:child_process";
import { mkdir, readFile } from "node:fs/promises";
import assert from "node:assert/strict";
import { chromium } from "@playwright/test";
import User from "../src/models/User.js";

const base = "http://localhost:3104";
let database, server, browser, cookie;
async function api(path, method = "GET", body) {
  const response = await fetch(`${base}/api${path}`, { method, headers: { "Content-Type": "application/json", Origin: base, ...(cookie ? { Cookie: cookie } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const result = await response.json();
  assert.ok(response.ok, result.message);
  return { ...result, response };
}
try {
  database = await MongoMemoryReplSet.create({ binary: { downloadDir: ".cache/mongodb" }, replSet: { count: 1 } });
  const uri = database.getUri("mobile_cart_test");
  await mongoose.connect(uri);
  const password = randomUUID();
  await User.create({ name: "Cart Tester", username: "carttester", passwordHash: await bcrypt.hash(password, 10), role: "ADMIN", active: true });
  server = spawn(process.execPath, ["node_modules/next/dist/bin/next", "start", "--port", "3104"], { windowsHide: true, stdio: "ignore", env: { ...process.env, MONGODB_URI: uri, MONGODB_DB_NAME: "mobile_cart_test", JWT_SECRET: randomUUID().repeat(2) } });
  for (let i = 0; i < 60; i++) {
    try { if ((await fetch(`${base}/login`)).ok) break; } catch {}
    await new Promise(resolve => setTimeout(resolve, 500));
  }
  const login = await api("/auth/login", "POST", { username: "carttester", password });
  cookie = login.response.headers.get("set-cookie").split(";")[0];
  const category = (await api("/categories", "POST", { name: "Test Juice", active: true })).data;
  for (let i = 1; i <= 20; i++) await api("/products", "POST", { name: `Juice ${String(i).padStart(2, "0")}`, imageUrl: 'https://res.cloudinary.com/test/image/upload/karikku/products/mobile-test.jpg', categoryId: category._id, basePrice: 50, active: true, variantsEnabled: false, addonsEnabled: false, variants: [], addons: [] });
  await api("/day-sessions", "POST", { action: "open", openingCash: 0 });
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: "reduce" });
  const [name, value] = cookie.split("=");
  await context.addCookies([{ name, value, url: base }]);
  const page = await context.newPage();
  const imageBytes = await readFile('public/receipt-logo.jpeg');
  await page.route('https://res.cloudinary.com/test/**', route => route.fulfill({ contentType: 'image/jpeg', body: imageBytes }));
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${base}/pos`);
  await page.locator('.pos-product-card img').first().evaluate(img => img.decode());
  await mkdir('test-results', { recursive: true });
  for (const width of [320, 390, 440, 820]) {
    await page.setViewportSize({ width, height: 956 });
    const layout = await page.evaluate(() => ({ width: innerWidth, documentWidth: document.documentElement.scrollWidth, cards: [...document.querySelectorAll('.pos-product-card')].map(el => { const r = el.getBoundingClientRect(); return { left: r.left, right: r.right }; }) }));
    assert.ok(layout.documentWidth <= width + 1, `No document overflow beyond subpixel rounding at ${width}px: ${JSON.stringify(layout)}`);
    assert.ok(layout.cards.every(card => card.left >= 0 && card.right <= width), `Product cards fit at ${width}px`);
    const photo = await page.locator('.pos-product-card img').first().evaluate(img => {
      const bounds = img.getBoundingClientRect();
      const card = img.closest('.pos-product-card').getBoundingClientRect();
      return { width: bounds.width, height: bounds.height, cardWidth: card.width, ratio: img.naturalWidth / img.naturalHeight };
    });
    assert.ok(Math.abs(photo.width - (photo.cardWidth - 2)) < 1, 'Photo spans the card without inset side gaps');
    assert.ok(Math.abs(photo.width / photo.height - photo.ratio) < .01, 'Full photo keeps its natural proportions without cropping');
    await page.screenshot({ path: `test-results/product-grid-${width}.png` });
  }
  await page.setViewportSize({ width: 390, height: 844 });
  const bar = page.locator(".pos-mobile-summary");
  const sheet = page.locator(".mobile-cart-sheet");
  assert.equal(await page.locator("#current-sale").isVisible(), false);
  await bar.click();
  await sheet.waitFor();
  assert.equal(await sheet.getByRole("button", { name: "Proceed Payment" }).isEnabled(), false);
  await page.keyboard.press("Escape");
  for (let i = 1; i <= 20; i++) {
    await page.getByRole("button", { name: new RegExp(`Juice ${String(i).padStart(2, "0")}`) }).click();
    if (![4, 10, 20].includes(i)) continue;
    const scrollBefore = await page.evaluate(() => ({ window: scrollY, content: document.querySelector('.app-content')?.scrollTop }));
    await bar.click();
    await sheet.waitFor();
    assert.equal(await sheet.locator(".pos-cart-item").count(), i);
    assert.equal(await page.evaluate(() => document.body.style.overflow), "hidden");
    const footer = sheet.locator(".pos-cart-footer");
    const before = await footer.boundingBox();
    const list = sheet.locator(".pos-cart-items");
    assert.ok(await list.evaluate(el => el.clientHeight > 0 && getComputedStyle(el).overflowY === 'auto'), `${i} rows have a bounded scroll area`);
    if (i >= 10) assert.ok(await list.evaluate(el => el.scrollHeight > el.clientHeight), `${i} rows overflow inside list`);
    await list.evaluate(el => { el.scrollTop = el.scrollHeight; });
    const after = await footer.boundingBox();
    assert.equal(after.y, before.y, 'Footer stays fixed when items scroll');
    assert.ok(after.y + after.height <= 844, 'Footer stays inside viewport');
    await mkdir("test-results", { recursive: true });
    await page.screenshot({ path: `test-results/mobile-cart-${i}.png` });
    await sheet.getByRole("button", { name: "Close cart" }).click();
    const scrollAfter = await page.evaluate(() => ({ window: scrollY, content: document.querySelector('.app-content')?.scrollTop }));
    assert.deepEqual(scrollAfter, scrollBefore);
    assert.notEqual(await page.evaluate(() => document.body.style.overflow), "hidden");
  }
  assert.match(await bar.innerText(), /20 items.*1,000/);
  await bar.click();
  await sheet.getByRole('button', { name: 'Add note for Juice 01', exact: true }).click();
  await sheet.getByRole('textbox', { name: 'Note for Juice 01', exact: true }).fill('Less ice');
  await sheet.getByRole('button', { name: 'Close cart', exact: true }).click();
  await bar.click();
  assert.equal(await sheet.getByRole('textbox', { name: 'Note for Juice 01', exact: true }).inputValue(), 'Less ice');
  await sheet.getByRole("button", { name: "Increase Juice 01", exact: true }).click();
  assert.match(await bar.innerText(), /21 items.*1,050/);
  await sheet.getByRole("button", { name: "Decrease Juice 01", exact: true }).click();
  await sheet.getByRole("button", { name: "Remove Juice 01", exact: true }).click();
  assert.match(await bar.innerText(), /19 items.*950/);
  await sheet.getByLabel("Discount value", { exact: true }).fill("50");
  assert.match(await bar.innerText(), /19 items.*900/);
  await sheet.getByRole("button", { name: "Proceed Payment" }).click();
  await page.locator(".checkout-methods").waitFor();
  assert.equal(await sheet.count(), 0);
  assert.equal(await page.evaluate(() => document.body.style.overflow), "hidden", 'Payment modal retains body lock');
  await page.keyboard.press("Escape");
  assert.notEqual(await page.evaluate(() => document.body.style.overflow), "hidden");
  await bar.click();
  await page.mouse.click(10, 10);
  await sheet.waitFor({ state: "detached" });
  await bar.click();
  const expandHandle = await sheet.locator('.mobile-cart-handle').boundingBox();
  await page.mouse.move(expandHandle.x + expandHandle.width / 2, expandHandle.y + 22);
  await page.mouse.down();
  await page.mouse.move(expandHandle.x + expandHandle.width / 2, expandHandle.y - 55, { steps: 6 });
  await page.mouse.up();
  assert.equal(await sheet.getAttribute('data-expanded'), 'true');
  assert.ok(Math.abs((await sheet.boundingBox()).height - 844) < 2);
  assert.ok(Math.abs((await sheet.boundingBox()).y) < 2);
  const fullHandle = await sheet.locator('.mobile-cart-handle').boundingBox();
  await page.mouse.move(fullHandle.x + fullHandle.width / 2, fullHandle.y + 22);
  await page.mouse.down();
  await page.mouse.move(fullHandle.x + fullHandle.width / 2, fullHandle.y + 100, { steps: 6 });
  await page.mouse.up();
  assert.equal(await sheet.getAttribute('data-expanded'), 'false');
  const handle = await sheet.locator('.mobile-cart-handle').boundingBox();
  await page.mouse.move(handle.x + handle.width / 2, handle.y + 10);
  await page.mouse.down();
  await page.mouse.move(handle.x + handle.width / 2, handle.y + 80, { steps: 6 });
  await page.mouse.up();
  await sheet.waitFor({ state: 'detached' });
  await page.setViewportSize({ width: 820, height: 1180 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await bar.click();
  assert.equal(await sheet.evaluate(el => getComputedStyle(el).animationName), 'mobile-cart-enter');
  await page.screenshot({ path: "test-results/tablet-cart.png" });
  await sheet.getByRole('button', { name: 'Expand cart to full screen' }).click();
  await page.waitForFunction(() => Math.abs(document.querySelector('.mobile-cart-sheet').getBoundingClientRect().height - innerHeight) < 2);
  assert.equal(await sheet.evaluate(el => getComputedStyle(el).transitionDuration.split(',')[0]), '0.26s');
  await page.screenshot({ path: 'test-results/tablet-cart-fullscreen.png' });
  const expandedFooter = await sheet.locator('.pos-cart-footer').boundingBox();
  assert.ok(expandedFooter.y + expandedFooter.height <= 1181);
  await sheet.getByRole('button', { name: 'Restore cart sheet' }).press('Enter');
  await page.waitForFunction(() => Math.abs(document.querySelector('.mobile-cart-sheet').getBoundingClientRect().height - innerHeight * .85) < 2);
  await page.keyboard.press('Escape');
  assert.equal(await sheet.getAttribute('data-state'), 'closing');
  assert.equal(await sheet.evaluate(el => getComputedStyle(el).animationName), 'mobile-cart-exit');
  assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden');
  await sheet.waitFor({ state: 'detached' });
  assert.notEqual(await page.evaluate(() => document.body.style.overflow), 'hidden');
  await bar.click();
  await page.setViewportSize({ width: 1280, height: 900 });
  await sheet.waitFor({ state: "detached" });
  assert.equal(await bar.isVisible(), false);
  assert.equal(await page.locator("#current-sale").isVisible(), true);
  assert.equal(await page.locator("#current-sale .pos-cart-item").count(), 19);
  assert.equal(await page.locator("#current-sale").evaluate(el => getComputedStyle(el).position), "fixed");
  await page.screenshot({ path: "test-results/desktop-cart-unchanged.png" });
  assert.deepEqual(errors, []);
  console.log("PASS: empty cart, 4/10/20 row scrolling, fixed footer, live quantity/removal/discount totals, scroll restoration, Escape/backdrop dismissal, checkout handoff, tablet, desktop breakpoint and preserved cart state.");
} finally {
  await browser?.close();
  server?.kill();
  await mongoose.disconnect();
  await database?.stop();
}
